import assert from 'node:assert/strict';
globalThis.self=globalThis;
const {default:GeoTIFF}=await import('../assets/vendor/geotiff-2.1.4-beta.0.js');
const {rasterJoin}=await import('../resources/raster-join-worker.js');
const {default:{project}}=await import('../assets/vendor/shp-6.1.0.js');
const t=GeoTIFF.writeArrayBuffer([2,2,8,255],{width:2,height:2,BitsPerSample:[8],SampleFormat:[1],SamplesPerPixel:1,ModelPixelScale:[1,1,0],ModelTiepoint:[0,0,0,30,-25,0],GeographicTypeGeoKey:4326,GTRasterTypeGeoKey:1,GTModelTypeGeoKey:2,GDAL_NODATA:'255'});
const point=(x,y)=>({type:'Point',coordinates:[x,y]});
const poly={type:'Polygon',coordinates:[[[30,-25],[32,-25],[32,-27],[30,-27],[30,-25]]]};
const geometries=[point(30.25,-25.25),point(31.75,-26.75),point(36,-26),poly,{type:'LineString',coordinates:[[30.1,-26.1],[30.9,-26.1]]}];
const source={type:'FeatureCollection',features:geometries.map((geometry,i)=>({type:'Feature',properties:{id:i},geometry}))};
const options={raster:new File([t],'fixture.tif'),vector:new File([JSON.stringify(source)],'fixture.geojson'),band:1,field:'value',statistic:'mean'};
const result=await rasterJoin(options);
assert.deepEqual(result.data.features.map(f=>f.properties.value),[2,null,null,4,8]);
assert.deepEqual(result.data.features.map(f=>f.geometry),geometries);
assert.equal(result.matched,3);assert.equal(result.data.features[4].properties.id,4);
assert.equal((await rasterJoin({...options,statistic:'mode'})).data.features[3].properties.value,2);
await assert.rejects(rasterJoin({...options,field:'id'}),/already exists/);
await assert.rejects(rasterJoin({...options,band:2}),/1 band/);
const [x,y]=project('EPSG:4326','EPSG:3857',[31,-26]);
const projected=GeoTIFF.writeArrayBuffer([19,20,21,22],{width:2,height:2,BitsPerSample:[8],SampleFormat:[1],SamplesPerPixel:1,ModelPixelScale:[100,100,0],ModelTiepoint:[0,0,0,x-50,y+50,0],ProjectedCSTypeGeoKey:3857,GTModelTypeGeoKey:1,GTRasterTypeGeoKey:1});
const check=await rasterJoin({...options,raster:new File([projected],'projected.tif'),vector:new File([JSON.stringify(point(31,-26))],'point.geojson')});
assert.equal(check.data.features[0].properties.value,19);
console.log('PASS: GeoTIFF decode and reprojection, points and lines, polygon statistics, NoData, unchanged geometry and attributes, validation.');
